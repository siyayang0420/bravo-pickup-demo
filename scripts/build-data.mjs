// Builds js/data.js from data/stores.json (20 stores from Bravo's catalog) and data/menus.mjs (the authored menus).
//   node scripts/build-data.mjs                                  rebuild from the saved stores
//   BRAVO_WEB_BASE=https://…/web node scripts/build-data.mjs --refresh   pull the 20 stores again first
import fs from 'node:fs'
import menus from '../data/menus.mjs'

const file = p => new URL(`../${p}`, import.meta.url)
const PICKUP_DISCOUNT = 0.2 // featured items only

if (process.argv.includes('--refresh')) {
  const base = process.env.BRAVO_WEB_BASE
  if (!base) throw new Error('Set BRAVO_WEB_BASE to the /web backend (NUXT_BACKEND_WEB_BASE in bravo_web_client_v2/.env)')
  const stores = []
  for (const id of Object.keys(menus)) {
    const res = await fetch(`${base}/store`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ id: Number(id) }) })
    const s = (await res.json()).data
    if (!s?.id) throw new Error(`store ${id}: HTTP ${res.status}`)
    stores.push({
      id: s.id, name: s.name, logo: s.logo, cuisine: s.cuisine, city: s.city, address: s.address,
      rating: s.rating, rating_count: s.rating_count, average_price: s.average_price, tags: s.tags ?? [],
      hours: s.opening_hours?.periods ?? [],
      photos: (s.store_images ?? []).slice(0, 5).map(i => i.image),
      dishes: (s.recommend_dishes ?? []).filter(d => d.name && d.image).map(d => ({ name: d.name.trim(), image: d.image })),
    })
  }
  fs.writeFileSync(file('data/stores.json'), JSON.stringify(stores, null, 1) + '\n')
  console.log(`Saved ${stores.length} stores to data/stores.json`)
}

const norm = s => s.toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim()
const stores = JSON.parse(fs.readFileSync(file('data/stores.json'), 'utf8')).map((s) => {
  const m = menus[s.id]
  if (!m) throw new Error(`${s.name}: no menu in data/menus.mjs`)
  // Bravo's own dish photos, with names tidied up where the catalog has typos
  const rename = new Map(Object.entries(m.rename ?? {}).map(([from, to]) => [norm(from), to]))
  const skip = new Set((m.skip ?? []).map(norm))
  const real = s.dishes.filter(d => !skip.has(norm(d.name))).map(d => ({ ...d, name: rename.get(norm(d.name)) ?? d.name }))
  const photo = new Map(real.map(d => [norm(d.name), d.image]))

  let n = 0
  const menu = Object.entries(m.menu).map(([title, lines]) => ({
    title,
    items: lines.map((line) => {
      const [name, price, desc] = line.split(' | ')
      return { id: `${s.id}-${++n}`, name, price: Number(price), desc, image: photo.get(norm(name)) }
    }),
  }))
  const items = menu.flatMap(c => c.items)
  if (items.length < 20 || items.length > 30) throw new Error(`${s.name}: ${items.length} dishes, expected 20–30`)

  const featured = real.map((d) => {
    const item = items.find(i => norm(i.name) === norm(d.name))
    if (!item) throw new Error(`${s.name}: "${d.name}" has a photo but isn't on the menu`)
    item.pickup = Math.round(item.price * (1 - PICKUP_DISCOUNT) * 100) / 100
    return item.id
  })

  const { dishes, ...store } = s
  return { ...store, ready: m.ready, featured, menu }
})

fs.writeFileSync(file('js/data.js'), `// Generated by scripts/build-data.mjs from data/stores.json and data/menus.mjs. Don't edit by hand.\nwindow.STORES = ${JSON.stringify(stores)}\n`)
console.log(stores.map(s => `${String(s.menu.flatMap(c => c.items).length).padStart(2)} dishes, ${s.featured.length} with photos  ${s.name}`).join('\n'))
